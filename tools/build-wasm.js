/*
 * build-wasm.js - rebuild the C++ WebAssembly kernel and its browser loader.
 *
 *   node tools/build-wasm.js
 *
 * Requires Zig (which bundles clang + wasm-ld). No Emscripten, no libc, no
 * network access. The generated js/wasm-module.js inlines the binary as
 * base64 so the module also works from file:// and inside Web Workers,
 * where fetch() of a .wasm file would be blocked by CORS.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const src = path.join(root, 'native', 'tiling_core.cpp');
const out = path.join(root, 'wasm', 'tiling_core.wasm');
const loader = path.join(root, 'js', 'wasm-module.js');
const zig = process.env.ZIG || 'zig';

fs.mkdirSync(path.dirname(out), { recursive: true });
// Use workspace-relative paths: the workspace directory may contain spaces,
// which would be split incorrectly when a shell is involved.
const args = [
  'c++', '-target', 'wasm32-freestanding', '-O3',
  '-fno-exceptions', '-fno-rtti', '-nostdlib',
  '-Wl,--no-entry', '-Wl,--import-memory', '-Wl,--export=__heap_base',
  '-o', 'wasm/tiling_core.wasm', 'native/tiling_core.cpp'
];
console.log('[1/3] compiling native/tiling_core.cpp');
execFileSync(zig, args, { stdio: 'inherit', cwd: root });

const bin = fs.readFileSync(out);
if (bin.subarray(0, 4).toString('hex') !== '0061736d') throw new Error('bad wasm magic');
const sha = crypto.createHash('sha256').update(bin).digest('hex').slice(0, 16);
console.log('[2/3] wasm bytes=' + bin.length + ' sha256=' + sha);

const b64 = bin.toString('base64');
const js = `/* Auto-generated by tools/build-wasm.js - DO NOT EDIT BY HAND.
 * C++ source: native/tiling_core.cpp | sha256: ${sha} | bytes: ${bin.length}
 * Inlined so Workers can instantiate the module without a network fetch. */
(function (root) {
  'use strict';
  var B64 = '${b64}';
  var cached = null;
  function bytes() {
    if (cached) return cached;
    var raw = typeof atob === 'function'
      ? atob(B64)
      : Buffer.from(B64, 'base64').toString('binary');
    var u8 = new Uint8Array(raw.length);
    for (var i = 0; i < raw.length; i++) u8[i] = raw.charCodeAt(i);
    cached = u8;
    return u8;
  }
  root.WasmModule = {
    bytes: bytes,
    sha: '${sha}',
    size: ${bin.length},
    compile: function () { return WebAssembly.compile(bytes()); }
  };
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
fs.writeFileSync(loader, js);
console.log('[3/3] wrote ' + path.relative(root, loader) + ' (' + js.length + ' bytes)');
WebAssembly.compile(bin).then(function (m) {
  console.log('exports:', WebAssembly.Module.exports(m).map(function (e) { return e.name; }).join(', '));
  console.log('imports:', WebAssembly.Module.imports(m).map(function (e) { return e.module + '.' + e.name; }).join(', '));
}).catch(function (e) { console.error(e); process.exit(1); });
